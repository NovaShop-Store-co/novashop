create or replace function public.handle_new_novashop_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles(id,full_name)
  values(new.id,coalesce(new.raw_user_meta_data ->> 'full_name',''))
  on conflict(id) do nothing;
  return new;
end;
$$;
revoke execute on function public.handle_new_novashop_user() from public,anon,authenticated;
drop trigger if exists on_novashop_auth_user_created on auth.users;
create trigger on_novashop_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_novashop_user();

