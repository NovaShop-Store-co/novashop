create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default ('NS-' || upper(substr(encode(gen_random_bytes(8),'hex'),1,10))),
  user_id uuid references auth.users(id) on delete set null,
  status text not null default 'pending_payment' check (status in ('pending_payment','paid','preparing','shipped','delivered','cancelled','payment_failed','refunded')),
  payment_status text not null default 'pending' check (payment_status in ('pending','approved','rejected','cancelled','refunded')),
  payment_provider text, payment_reference text,
  shipping_fee_cop bigint check (shipping_fee_cop is null or shipping_fee_cop >= 0),
  shipping_payment_status text not null default 'not_required'
    check (shipping_payment_status in ('not_required','pending','approved')),
  currency text not null default 'COP' check (currency='COP'),
  subtotal_cop bigint not null check (subtotal_cop > 0),
  delivery_type text not null check (delivery_type in ('physical','digital','mixed')),
  customer_first_name text not null, customer_last_name text not null,
  customer_email text, customer_phone text not null,
  address text, neighborhood text, city text, department text, postal_code text,
  delivery_reference text, preferred_payment_method text, customer_note text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id integer not null references public.products(id),
  product_name text not null, unit_price_cop bigint not null check (unit_price_cop > 0),
  quantity integer not null check (quantity between 1 and 10),
  line_total_cop bigint generated always as (unit_price_cop * quantity) stored,
  delivery_type text not null check (delivery_type in ('physical','digital')),
  selected_variant text,
  created_at timestamptz not null default now()
);

-- Keep Dropi identifiers in private tables, not the public catalog or customer-visible order_items.
create table if not exists public.product_supplier_refs (
  product_id integer primary key references public.products(id) on delete cascade,
  dropi_product_id text not null unique,
  updated_at timestamptz not null default now(),
  constraint product_supplier_refs_dropi_id_nonempty
    check (length(btrim(dropi_product_id)) between 1 and 100)
);

create table if not exists public.order_item_supplier_refs (
  order_item_id bigint primary key references public.order_items(id) on delete cascade,
  dropi_product_id text not null
    check (length(btrim(dropi_product_id)) between 1 and 100),
  created_at timestamptz not null default now()
);

alter table public.product_supplier_refs enable row level security;
alter table public.order_item_supplier_refs enable row level security;

revoke all on table public.product_supplier_refs from anon, authenticated;
revoke all on table public.order_item_supplier_refs from anon, authenticated;
grant all on table public.product_supplier_refs to service_role;
grant all on table public.order_item_supplier_refs to service_role;

create index if not exists product_supplier_refs_dropi_id_idx
  on public.product_supplier_refs(dropi_product_id);
create index if not exists order_item_supplier_refs_dropi_id_idx
  on public.order_item_supplier_refs(dropi_product_id);

