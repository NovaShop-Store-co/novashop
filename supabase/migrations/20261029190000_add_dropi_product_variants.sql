-- Dropi variants by cut, color and size. Supplier IDs and supplier costs stay private.
create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id integer not null references public.products(id) on delete cascade,
  audience text not null check (audience in ('hombre','mujer')),
  color text not null check (char_length(btrim(color)) between 1 and 40),
  size text not null check (char_length(btrim(size)) between 1 and 24),
  stock_quantity integer not null default 0 check (stock_quantity >= 0),
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, audience, color, size)
);

create index if not exists product_variants_product_active_idx
  on public.product_variants(product_id, is_active, sort_order, audience, color, size);

create table if not exists public.product_variant_supplier_refs (
  product_variant_id bigint primary key references public.product_variants(id) on delete cascade,
  dropi_variant_id text not null unique check (char_length(btrim(dropi_variant_id)) between 1 and 100),
  supplier_price_cop bigint null check (supplier_price_cop is null or supplier_price_cop >= 0),
  updated_at timestamptz not null default now()
);

alter table public.product_variants enable row level security;
alter table public.product_variant_supplier_refs enable row level security;
revoke all on table public.product_variants from anon, authenticated;
grant select on table public.product_variants to anon, authenticated;
revoke all on table public.product_variant_supplier_refs from anon, authenticated;
revoke all on table public.product_variant_supplier_refs from public;
grant all on table public.product_variant_supplier_refs to service_role;

drop policy if exists "Public can read active product variants" on public.product_variants;
create policy "Public can read active product variants" on public.product_variants
for select to anon, authenticated
using (
  is_active = true and exists (
    select 1 from public.products p
    where p.id = product_id and p.is_active = true
  )
);

alter table public.order_items add column if not exists selected_audience text null;
alter table public.order_items drop constraint if exists order_items_selected_audience_check;
alter table public.order_items add constraint order_items_selected_audience_check
  check (selected_audience is null or selected_audience in ('hombre','mujer'));

comment on table public.product_variants is 'Public buyer options by cut, color and size; contains no supplier IDs or costs.';
comment on table public.product_variant_supplier_refs is 'Private mapping from NovaShop variants to Dropi variant IDs and supplier prices.';
comment on column public.order_items.selected_audience is 'Selected cut: hombre or mujer.';